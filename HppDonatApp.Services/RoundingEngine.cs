    public static decimal RoundTo(decimal value, string rule)
    {
        if (string.IsNullOrWhiteSpace(rule))
        {
            return Math.Round(value, 0, MidpointRounding.AwayFromZero);
        }
        return rule switch
        {
            "Nearest100" => RoundNearest(value, 100m),
            "Nearest500" => RoundNearest(value, 500m),
            "Nearest1000" => RoundNearest(value, 1000m),
            "Psychological990" => RoundPsychological(value, 990m),
            "Significant2" => RoundSignificant(value, 2),
            _ => Math.Round(value, 0, MidpointRounding.AwayFromZero),
        };
    }

    public static decimal RoundNearest(decimal value, decimal step)
    {
        if (step <= 0m)
        {
            return value;
        }
        return Math.Round(value / step, 0, MidpointRounding.AwayFromZero) * step;
    }

    public static decimal RoundPsychological(decimal value, decimal ending)
    {
        if (value <= 0m)
        {
            return value;
        }
        var magnitude = Math.Pow(10, Math.Max(0, Math.Floor(Math.Log10((double)value)) - 2));
        var baseValue = Math.Floor(value / (decimal)magnitude) * (decimal)magnitude;
        var candidate = baseValue + ending;
        if (candidate < value)
        {
            candidate += (decimal)magnitude;
        }
        return candidate;
    }

    public static decimal RoundSignificant(decimal value, int digits)
    {
        if (value == 0m)
        {
            return 0m;
        }
        var scale = Math.Pow(10, digits - 1 - Math.Floor(Math.Log10(Math.Abs((double)value))));
        return Math.Round(value * (decimal)scale, 0, MidpointRounding.AwayFromZero) / (decimal)scale;
    }

